    private long countByCategory(String category) {
        return documents.stream().filter(d -> category.equals(d.category())).count();
    }

    /**
     * 检索相关文档，按匹配得分排序，返回前3篇
     */
    public List<MentalHealthDocument> retrieve(String query) {
        if (query == null || query.isBlank()) {
            return List.of();
        }
        return documents.stream()
                .map(doc -> new ScoredDocument(doc, doc.calculateScore(query)))
                .filter(item -> item.score() > 0)
                .sorted(Comparator.comparingInt(ScoredDocument::score).reversed())
                .limit(3)
                .map(ScoredDocument::document)
                .toList();
    }

    /**
     * 按场景分类检索
     */
    public List<MentalHealthDocument> retrieveByCategory(String category) {
        if (category == null || category.isBlank()) {
            return List.of();
        }
        return documents.stream()
                .filter(doc -> category.equals(doc.category()))
                .toList();
    }

    /**
     * 构建带引用的知识上下文
     */
    public String buildContext(String query) {
        List<MentalHealthDocument> results = retrieve(query);
        if (results.isEmpty()) {
            return "";
        }
        StringBuilder context = new StringBuilder();
        for (MentalHealthDocument doc : results) {
            context.append("【").append(doc.title()).append("】\n")
                    .append(doc.content()).append("\n")
                    .append("来源：").append(doc.source())
                    .append("（更新于 ").append(doc.updateTime()).append("）\n\n");
        }
        return context.toString().trim();
    }

    /**
     * 获取所有文档
     */
    public List<MentalHealthDocument> getAllDocuments() {
        return documents;
    }

